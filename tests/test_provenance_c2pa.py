def _detailed_payload(*, validation_state: str = "Valid", failures: list[str] | None = None) -> dict:
    return {
        "active_manifest": "urn:uuid:11111111-2222-3333-4444-555555555555",
        "validation_state": validation_state,
        "validation_results": {
            "activeManifest": {
                "success": [{"code": "claimSignature.validated"}],
                "failure": [{"code": code} for code in (failures or [])],
            }
        },
        "manifests": {
            "urn:uuid:11111111-2222-3333-4444-555555555555": {
                "claim": {
                    "claim_generator_info": [{"name": "chatcut", "version": "1.2.0"}],
                    "signature": {
                        "issuer": "Example Issuer CA",
                        "common_name": "Example Signer",
                        "time": "2026-09-24T10:00:00+00:00",
                    },
                },
                "assertion_store": {
                    "c2pa.hash.data": {"alg": "sha256", "hash": "abc"},
                    "c2pa.actions.v2": {
                        "actions": [
                            {
                                "action": "c2pa.created",
                                "digitalSourceType": (
                                    "http://cv.iptc.org/newscodes/digitalsourcetype/"
                                    "trainedAlgorithmicMedia"
                                ),
                            },
                            {
                                "action": "c2pa.opened",
                                "digitalSourceType": (
                                    "http://cv.iptc.org/newscodes/digitalsourcetype/"
                                    "digitalCapture"
                                ),
                            },
                        ]
                    },
                },
            }
        },
    }


def test_summary_extracts_signer_and_generative_source_type() -> None:
    summary = ProvenanceAnalyzer._c2pa_summary(_detailed_payload())

    assert summary["validation_state"] == "Valid"
    assert summary["issuer"] == "Example Issuer CA"
    assert summary["claim_generator"] == "chatcut 1.2.0"
    assert summary["signing_time"] == "2026-09-24T10:00:00+00:00"
    assert len(summary["digital_source_types"]) == 2
    assert summary["ai_digital_source_types"] == [
        "C2PA digitalSourceType=trainedAlgorithmicMedia"
    ]


def test_summary_handles_missing_manifest_payload() -> None:
    summary = ProvenanceAnalyzer._c2pa_summary(None)

    assert summary["active_manifest"] is None
    assert summary["ai_digital_source_types"] == []


def test_explanation_reports_invalid_claim_and_failures() -> None:
    summary = ProvenanceAnalyzer._c2pa_summary(
        _detailed_payload(validation_state="Invalid", failures=["claimSignature.mismatch"])
    )
    explanation = ProvenanceAnalyzer._c2pa_explanation(summary)

    assert "未通过" in explanation
    assert "Example Issuer CA" in explanation
    assert "claimSignature.mismatch" in explanation


