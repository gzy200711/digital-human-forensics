def _context(tmp_path: Path) -> PluginContext:
    stream = MediaStream(
        index=0,
        codec_type="video",
        codec_name="h264",
        width=720,
        height=1280,
        frame_rate=25.0,
        sample_rate=None,
        channels=None,
        duration_seconds=8.0,
        tags={},
    )
    probe = MediaProbe(
        path=tmp_path / "sample.mp4",
        format_name="mov,mp4,m4a",
        format_long_name="QuickTime / MOV",
        duration_seconds=8.0,
        size_bytes=4096,
        bit_rate=800000,
        tags={},
        streams=[stream],
    )
    return PluginContext(
        job_id="provenance",
        original_filename="sample.mp4",
        source_object_key="samples/sample.mp4",
        media_path=probe.path,
        probe=probe,
        settings=None,
    )


def test_c2pa_manifest_without_ai_source_is_not_hard_positive(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    summary = ProvenanceAnalyzer._c2pa_summary(
        _detailed_payload(validation_state="Valid")
    )
    summary["ai_digital_source_types"] = []
    monkeypatch.setattr(
        ProvenanceAnalyzer,
        "_check_c2pa",
        staticmethod(lambda _context: {
            "name": "C2PA / Content Credentials",
            "status": "阳性",
            "positive": True,
            "details": {
                "summary": summary,
                "ai_digital_source_types": [],
                "ai_evidence_eligible": True,
            },
            "explanation": "camera capture manifest",
        }),
    )
    monkeypatch.setattr("shutil.which", lambda _name: None)

    result = ProvenanceAnalyzer().analyze(_context(tmp_path))

    assert result.explicit_ai_indicators == []


def test_invalid_c2pa_ai_source_stays_unverified(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    summary = ProvenanceAnalyzer._c2pa_summary(
        _detailed_payload(
            validation_state="Invalid",
            failures=["claimSignature.mismatch"],
        )
    )
    monkeypatch.setattr(
        ProvenanceAnalyzer,
        "_check_c2pa",
        staticmethod(lambda _context: {
            "name": "C2PA / Content Credentials",
            "status": "阳性",
            "positive": True,
            "details": {
                "summary": summary,
                "ai_digital_source_types": summary["ai_digital_source_types"],
                "ai_evidence_eligible": ProvenanceAnalyzer._c2pa_ai_evidence_eligible(
                    summary
                ),
            },
            "explanation": ProvenanceAnalyzer._c2pa_explanation(summary),
        }),
    )
    monkeypatch.setattr("shutil.which", lambda _name: None)

    result = ProvenanceAnalyzer().analyze(_context(tmp_path))

    assert result.explicit_ai_indicators == []
